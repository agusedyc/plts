export async function fetchBatteriesDatabase(url = 'data/batteries.json') {
  try {
    const res = await fetch(url);
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        return data;
      }
    }
  } catch {
    // Fallback to default batteries
  }
  return DEFAULT_BATTERIES;
}

export function findBatteryById(id, batteries = DEFAULT_BATTERIES) {
  return batteries.find((b) => b.id === id) || null;
}

export function filterBatteriesByVoltage(voltage, batteries = DEFAULT_BATTERIES) {
  const v = Number(voltage) || 48;
  return batteries.filter((b) => {
    const sysV = Number(b.systemVoltage || b.voltage);
    const volt = Number(b.voltage);
    if (v === 48) {
      return sysV === 48 || volt === 48 || volt === 51.2;
    }
    if (v === 24) {
      return sysV === 24 || volt === 24 || volt === 25.6;
    }
    if (v === 12) {
      return sysV === 12 || volt === 12 || volt === 12.8;
    }
    return sysV === v;
  });
}
